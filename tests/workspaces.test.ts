import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { spawn } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';

test('owner and two independently authenticated members isolate items, inbound bridges and logout under concurrent requests',async()=>{
  const directory=mkdtempSync(join(tmpdir(),'daylight-tenants-'));
  const forwarded:string[]=[];
  const auth=createServer((request,response)=>{
    const cookie=request.headers.cookie || '';forwarded.push(cookie);
    const id=cookie.includes('member-a')?'member-a':cookie.includes('member-b')?'member-b':null;
    response.setHeader('Content-Type','application/json');
    response.end(JSON.stringify(id?{user:{id,name:id,email:`${id}@example.invalid`,emailVerified:true,createdAt:new Date().toISOString(),updatedAt:new Date().toISOString(),image:null},session:{id:`session-${id}`,userId:id,token:id,expiresAt:new Date(Date.now()+3600000).toISOString(),createdAt:new Date().toISOString(),updatedAt:new Date().toISOString(),ipAddress:null,userAgent:null}}:null));
  });
  await new Promise<void>(resolve=>auth.listen(0,'127.0.0.1',resolve));
  const authPort=(auth.address() as {port:number}).port;
  const port=41000+Math.floor(Math.random()*10000);const origin=`http://127.0.0.1:${port}`;
  const password='synthetic-owner-password-only';
  const child=spawn(process.execPath,['--import','tsx','server/index.ts'],{env:{...process.env,DATABASE_URL:'',VERCEL:'',NODE_ENV:'test',PORT:String(port),APP_ORIGIN:origin,APP_PASSWORD:password,DATA_DIR:directory,ENCRYPTION_KEY:'ab'.repeat(32),NEON_AUTH_BASE_URL:`http://127.0.0.1:${authPort}`,STORE_NAMESPACE:'isolation:'},stdio:'ignore'});
  const headers=(cookie:string)=>({'Content-Type':'application/json',Origin:origin,Cookie:cookie});
  const request=async(path:string,cookie:string,method='GET',body?:unknown)=>fetch(origin+path,{method,headers:headers(cookie),...(body?{body:JSON.stringify(body)}:{})});
  try{
    let ready=false;for(let n=0;n<200;n++){try{if((await fetch(origin+'/api/health')).ok){ready=true;break;}}catch{}await delay(100);}assert.ok(ready);
    const login=await request('/api/login','','POST',{password});assert.equal(login.status,200);
    const owner=login.headers.getSetCookie().find(v=>v.startsWith('daylight='))!.split(';')[0];
    const a='__Secure-neon-auth.session_token=member-a';const b='__Secure-neon-auth.session_token=member-b';
    const ownerTask=await (await request('/api/tasks',owner,'POST',{title:'Owner private task',due:null})).json();
    assert.equal((await (await request('/api/dashboard',a)).json()).items.length,0);
    assert.equal((await (await request('/api/dashboard',b)).json()).items.length,0);
    const writes=await Promise.all(Array.from({length:8},(_,i)=>request('/api/tasks',i%2?a:b,'POST',{title:`Private ${i%2?'A':'B'} ${i}`,due:null})));
    assert.ok(writes.every(r=>r.ok));
    const aItems=(await (await request('/api/dashboard',a)).json()).items;
    const bItems=(await (await request('/api/dashboard',b)).json()).items;
    assert.equal(aItems.length,4);assert.ok(aItems.every((i:any)=>i.title.startsWith('Private A')));
    assert.equal(bItems.length,4);assert.ok(bItems.every((i:any)=>i.title.startsWith('Private B')));
    assert.equal((await request(`/api/items/${encodeURIComponent(ownerTask.id)}`,b,'PATCH',{completed:true})).status,404);
    const setupA=await (await request('/api/imports/gmail/setup',a,'POST',{})).json();
    const setupB=await (await request('/api/imports/gmail/setup',b,'POST',{})).json();
    const keyA=JSON.parse(setupA.code.match(/const DAYLIGHT = (.+);/)[1]).key;
    const keyB=JSON.parse(setupB.code.match(/const DAYLIGHT = (.+);/)[1]).key;
    assert.notEqual(keyA,keyB);
    const mail=await fetch(origin+'/api/imports/gmail/receive',{method:'POST',headers:{'Content-Type':'application/json',Authorization:`Bearer ${keyA}`},body:JSON.stringify({messages:[{id:'abc123',subject:'Private A message',snippet:'For A only'}]})});assert.equal(mail.status,200);
    const afterA=await (await request('/api/dashboard',a)).json();const afterB=await (await request('/api/dashboard',b)).json();const afterOwner=await (await request('/api/dashboard',owner)).json();
    assert.equal(afterA.imports.gmail.receivedCount,1);assert.equal(afterA.notifications.pending,1);
    assert.equal(afterB.imports.gmail.receivedCount,0);assert.equal(afterOwner.items.length,1);assert.equal(afterOwner.items[0].title,'Owner private task');
    const endpoint='https://fcm.googleapis.com/tenant-isolation-synthetic';
    const subscription={endpoint,keys:{p256dh:'synthetic',auth:'synthetic'}};
    assert.equal((await request('/api/push',a,'POST',subscription)).status,200);
    assert.equal((await (await request('/api/push/status',a,'POST',{endpoint})).json()).registered,true);
    assert.equal((await request('/api/push',b,'POST',subscription)).status,200);
    assert.equal((await (await request('/api/push/status',a,'POST',{endpoint})).json()).registered,false);
    assert.equal((await (await request('/api/push/status',b,'POST',{endpoint})).json()).registered,true);
    assert.equal((await request('/api/workspace',owner,'DELETE',{confirm:'DELETE'})).status,400);
    assert.equal((await request('/api/workspace',a,'DELETE',{confirm:'DELETE'})).status,200);
    assert.equal((await (await request('/api/dashboard',a)).json()).items.length,0);
    assert.equal((await (await request('/api/dashboard',b)).json()).items.length,4);
    assert.equal((await (await request('/api/dashboard',owner)).json()).items.length,1);
    assert.equal((await fetch(origin+'/api/imports/gmail/receive',{method:'POST',headers:{'Content-Type':'application/json',Authorization:`Bearer ${keyA}`},body:JSON.stringify({messages:[]})})).status,401);
    assert.equal((await request('/api/dashboard',owner+'; __Secure-neon-auth.session_token=invalid')).status,401,'invalid member session cannot fall back to owner');
    assert.ok(forwarded.every(v=>!v.includes('daylight=')),'owner credential is never forwarded to auth provider');
    await request('/api/logout',a,'POST',{});
    assert.equal((await request('/api/dashboard',a)).status,401);
    assert.equal((await request('/api/dashboard',b)).status,200);
    assert.equal((await request('/api/dashboard',owner)).status,200);
  }finally{const stopped=new Promise<void>(resolve=>child.once('exit',()=>resolve()));child.kill('SIGTERM');await stopped;await new Promise<void>(resolve=>auth.close(()=>resolve()));rmSync(directory,{recursive:true,force:true});}
});
